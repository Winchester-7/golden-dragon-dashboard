/** График на ноябрь: кто работает днём и ночью в день месяца (1–30). */
export function rota(dayOfMonth) {
  const day = dayOfMonth % 2 === 0 ? ['Айгерим'] : ['Бакыт']
  if (dayOfMonth % 10 === 0) day.push(day[0] === 'Айгерим' ? 'Бакыт' : 'Айгерим')
  const night = dayOfMonth % 2 === 0 ? ['Нургуль'] : ['Жибек']
  return { day, night }
}
